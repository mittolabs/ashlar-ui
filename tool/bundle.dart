// Embeds registry/ (the component sources and registry.json) into the CLI, so the
// ashlar command works offline and a CLI version is a component version.
// Run from the repository root: dart run tool/bundle.dart
import 'dart:convert';
import 'dart:io';

void main() {
  final manifest = jsonDecode(File('registry/registry.json').readAsStringSync()) as Map<String, dynamic>;
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/bundle.dart from registry/. Do not edit by hand.')
    ..writeln('// ignore_for_file: lines_longer_than_80_chars')
    ..writeln()
    ..writeln("import 'component.dart';")
    ..writeln()
    ..writeln('/// Every component the ashlar command can add, by name.')
    ..writeln('const registry = <String, Component>{');
  for (final MapEntry(key: name, value: spec as Map<String, dynamic>) in manifest.entries) {
    out
      ..writeln("  '$name': Component(")
      ..writeln('    description: ${jsonEncode(spec['description'])},')
      ..writeln('    requires: ${jsonEncode(spec['requires'] ?? [])},')
      ..writeln('    packages: ${jsonEncode(spec['packages'] ?? [])},')
      ..writeln('    files: {');
    for (final file in (spec['files'] as List).cast<String>()) {
      final source = File('registry/$file').readAsStringSync();
      out.writeln("      '$file': ${_raw(source)},");
    }
    out
      ..writeln('    },')
      ..writeln('  ),');
  }
  out.writeln('};');
  File('packages/ashlar_ui/lib/src/registry.g.dart').writeAsStringSync(out.toString());
  stdout.writeln('bundled ${manifest.length} components');
}

// A raw string that can hold any source: triple quotes cannot appear in our sources.
String _raw(String s) {
  if (s.contains("'''")) throw StateError("a source contains '''");
  return "r'''$s'''";
}
