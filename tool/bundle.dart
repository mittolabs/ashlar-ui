// Embeds registry/ (the component sources and registry.json) into the CLI, so the
// ashlar command works offline and a CLI version is a component version.
// Run from the repository root: dart run tool/bundle.dart
import 'dart:convert';
import 'dart:io';

void main() {
  final manifest = jsonDecode(File('registry/registry.json').readAsStringSync()) as Map<String, dynamic>;
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/bundle.dart from registry/. Do not edit by hand.')
    ..writeln('// ignore_for_file: lines_longer_than_80_chars')
    ..writeln()
    ..writeln("import 'component.dart';")
    ..writeln()
    ..writeln('/// Every component the ashlar command can add, by name.')
    ..writeln('const registry = <String, Component>{');
  // Which item each file is, for reading which items a test uses.
  final itemOf = {
    for (final MapEntry(key: name, value: spec as Map<String, dynamic>) in manifest.entries)
      for (final file in (spec['files'] as List).cast<String>()) file: name,
  };
  for (final MapEntry(key: name, value: spec as Map<String, dynamic>) in manifest.entries) {
    final tests = (spec['tests'] as List? ?? []).cast<String>();
    // The items its tests import besides it: its tests are written once these are there.
    final testNeeds = <String>{
      for (final file in tests)
        for (final m in RegExp(r'package:ashlar_ui_gallery/ui/(\w+\.dart)')
            .allMatches(File('registry/$file').readAsStringSync()))
          itemOf[m[1]] ?? (throw StateError('$file imports ${m[1]}, which no item has')),
    }..remove(name);
    out
      ..writeln("  '$name': Component(")
      ..writeln('    description: ${jsonEncode(spec['description'])},')
      ..writeln('    requires: ${jsonEncode(spec['requires'] ?? [])},')
      ..writeln('    packages: ${jsonEncode(spec['packages'] ?? [])},')
      ..writeln('    block: ${spec['block'] == true},')
      ..writeln('    replaces: ${jsonEncode(spec['replaces'] ?? [])},')
      ..writeln('    files: {');
    for (final file in (spec['files'] as List).cast<String>()) {
      final source = File('registry/$file').readAsStringSync();
      out.writeln("      '$file': ${_raw(source)},");
    }
    out.writeln('    },');
    if (tests.isNotEmpty) {
      out
        ..writeln('    testNeeds: ${jsonEncode(testNeeds.toList()..sort())},')
        ..writeln('    tests: {');
      for (final file in tests) {
        out.writeln("      '${file.split('/').last}': ${_raw(File('registry/$file').readAsStringSync())},");
      }
      out.writeln('    },');
    }
    // The picture ashlar update --preview draws, and the widget in it.
    if (spec['preview'] case final String file) {
      final source = File('registry/$file').readAsStringSync();
      final widget = RegExp(r'class (\w+Demo) extends').firstMatch(source)![1];
      out
        ..writeln("    previewWidget: '$widget',")
        ..writeln('    preview: ${_raw(source)},');
    }
    out.writeln('  ),');
  }
  out.writeln('};');
  File('packages/ashlar_ui/lib/src/registry.g.dart').writeAsStringSync(out.toString());
  final blocks = manifest.values.where((s) => (s as Map)['block'] == true).length;
  stdout.writeln('bundled ${manifest.length - blocks} components and $blocks blocks');
}

// A raw string that can hold any source: triple quotes cannot appear in our sources.
String _raw(String s) {
  if (s.contains("'''")) throw StateError("a source contains '''");
  return "r'''$s'''";
}
